    private void btnSeguroGeneralActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSeguroGeneralActionPerformed
        
        if (sistemaSeguridad.isPuertaBloqueada()) {
        sistemaSeguridad.desbloquearPuerta();
        btnSeguroGeneral.setText("Activar Seguro");
    } else {
        sistemaSeguridad.bloquearPuerta();
        btnSeguroGeneral.setText("Desactivar Seguro");
        lblPuertaIzq.setVisible(false);
        lblPuertaDer.setVisible(false);

        for (tipoPuerta tipo : tipoPuerta.values()) {
            controlador.cerrarPuerta(tipo);
        }

        // Actualizar los textos de los botones
        btnDelIzq.setText("Abrir Del Izq");
        btnDelDer.setText("Abrir Del Der");
        btnTrasIzq.setText("Abrir Tras Izq");
        btnTrasDer.setText("Abrir Tras Der");
    }
    }//GEN-LAST:event_btnSeguroGeneralActionPerformed

