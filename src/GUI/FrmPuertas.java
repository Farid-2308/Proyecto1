    private void btnDelIzqActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDelIzqActionPerformed
        tipoPuerta tipo = tipoPuerta.DELANTERA_IZQUIERDA;
        if (sistemaSeguridad.isPuertaBloqueada()) {
            controlador.cerrarPuerta(tipo);
            return;
        }
        
    if (controlador.estaAbierta(tipo)) {
        controlador.cerrarPuerta(tipo);
        btnDelIzq.setText("Abrir Del Izq");
        lblPuertaIzq.setVisible(false);
    } else {
        controlador.abrirPuerta(tipo);
        btnDelIzq.setText("Cerrar Del Izq");
        lblPuertaIzq.setVisible(true);
    }
    }//GEN-LAST:event_btnDelIzqActionPerformed

